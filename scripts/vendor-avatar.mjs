// Build the QML-compatible, DOM-free engine from an inspected upstream checkout.
import fs from 'node:fs';
import { createRequire } from 'node:module';
const requireBuild = createRequire(process.env.AVATAR_BUILD_PACKAGE || import.meta.url);
const { transformSync } = requireBuild('esbuild');
import path from 'node:path';
import { stripTypeScriptTypes } from 'node:module';
import { execFileSync } from 'node:child_process';
const source = path.resolve(process.argv[2]);
const revision = execFileSync('git', ['-C', source, 'rev-parse', 'HEAD'], {encoding:'utf8'}).trim();
const modules = new Map();
function visit(name) {
  if (modules.has(name)) return;
  let code = stripTypeScriptTypes(fs.readFileSync(path.join(source,'packages/core/src',name),'utf8'));
  code = code.replace('cuts.flatMap((h) => h.polys)', 'cuts.reduce((all, h) => all.concat(h.polys), [])').replace('loops.flat()', 'loops.reduce((all, loop) => all.concat(loop), [])');
  const deps = [];
  code = code.replace(/import\s*\{([\s\S]*?)\}\s*from\s*['"]\.\/([^'"]+)['"];?/g, (_, bindings, dep) => {
    deps.push(dep);
    return 'const {' + bindings.replace(/\s+as\s+/g, ': ') + '} = modules[' + JSON.stringify(dep) + '];';
  });
  const exports = [...code.matchAll(/export\s+(?:function|const|let|class)\s+(\w+)/g)].map(m=>m[1]);
  code = code.replace(/export\s+(?=(function|const|let|class)\b)/g,'');
  if (/\bimport\s|\bexport\s/.test(code.replace(/\/\*[\s\S]*?\*\//g,'').replace(/\/\/[^\n]*/g,''))) throw Error('Unsupported module syntax: '+name);
  for (const dep of deps) visit(dep);
  modules.set(name, 'modules['+JSON.stringify(name)+'] = (function() {\n'+code+'\nreturn {'+exports.join(',')+'};\n})();');
}
visit('render.ts'); visit('validate.ts');
const result = '.pragma library\n// Open Bot Avatar, MIT, Copyright (c) 2026 Dominik Scholz.\n// Generated by scripts/vendor-avatar.mjs from '+revision+'.\nvar engine = (function() {\nconst modules = {};\n'+[...modules.values()].join('\n')+'\nreturn {validateAvatar: modules["validate.ts"].validateAvatar, avatarFrame: modules["render.ts"].avatarFrame};\n})();\nfunction validateAvatar(value) { return engine.validateAvatar(value); }\nfunction avatarFrame(value, options) { return engine.avatarFrame(value, options); }\n';
// Preserve QML's top-level exported functions after syntax lowering.
const lowered = transformSync(result.replace(/^\.pragma library\n/, ''), {target:'es2016', legalComments:'inline'}).code;
fs.writeFileSync('qml/openbotavatar.js','.pragma library\n// Open Bot Avatar, MIT, Copyright (c) 2026 Dominik Scholz. Upstream '+revision+'\n'+lowered);
fs.mkdirSync('licenses',{recursive:true});
fs.copyFileSync(path.join(source,'LICENSE'),'licenses/open-bot-avatar-MIT.txt');
fs.writeFileSync('data/open-bot-avatar-source.json',JSON.stringify({repository:'https://github.com/DominikScholz/open-bot-avatar',revision},null,2)+'\n');
